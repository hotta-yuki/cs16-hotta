"""
animation_player_for_npz.py — Play back FDTD simulation data stored in NPZ files.

Reads NPZ files generated by kukei_ani.py, kusabi_ani.py, or ushape_ani.py
and visualizes the wave propagation animation using Tkinter and Matplotlib.
"""
import numpy as np
import os
import argparse
import sys
import matplotlib.pyplot as plt
import traceback
import tkinter as tk
from tkinter import ttk, messagebox, filedialog
from matplotlib import animation
from matplotlib.patches import Rectangle
from matplotlib.backends.backend_tkagg import FigureCanvasTkAgg

def unique_path(path: str) -> str:
    if not os.path.exists(path):
        return path
    root, ext = os.path.splitext(path)
    k = 2
    while True:
        cand = f"{root}_v{k}{ext}"
        if not os.path.exists(cand):
            return cand
        k += 1

class IntegratedViewer:
    def __init__(self, root, data_dict, filepath):
        self.root = root
        self.filepath = filepath
        self.output_dir = os.path.dirname(filepath)
        
        # Load arrays and configuration
        self.g_t1 = data_dict["g_t1"]
        self.g_t3 = data_dict["g_t3"]
        self.g_t5 = data_dict["g_t5"]
        self.z_t1 = data_dict["z_t1"]
        self.z_t3 = data_dict["z_t3"]
        self.z_t5 = data_dict["z_t5"]
        self.time_step = float(data_dict["time_step"])
        self.extent_global = list(data_dict["extent_global"])
        self.extent_zoom = list(data_dict["extent_zoom"])
        self.roi_rect_mm = list(data_dict["roi_rect_mm"])
        self.base_name = str(data_dict["base_name"]) if "base_name" in data_dict else os.path.splitext(os.path.basename(filepath))[0]
        
        self.mask_matrix = data_dict["mask_matrix"] if "mask_matrix" in data_dict else None
            
        # Optional metadata
        self.probe_z_l_mm = float(data_dict["probe_z_l_mm"]) if "probe_z_l_mm" in data_dict else None
        self.probe_z_r_mm = float(data_dict["probe_z_r_mm"]) if "probe_z_r_mm" in data_dict else None
        self.probe_center_mm = float(data_dict["probe_center_mm"]) if "probe_center_mm" in data_dict else None
        self.gap_center_mm = float(data_dict["gap_center_mm"]) if "gap_center_mm" in data_dict else None

        # Normalize data (same as original simulation viewer)
        max_t1 = np.max(np.abs(self.g_t1))
        self.g_t1 = self.g_t1 / max_t1 if max_t1 > 1e-12 else self.g_t1
        self.z_t1 = self.z_t1 / max_t1 if max_t1 > 1e-12 else self.z_t1

        max_t3 = np.max(np.abs(self.g_t3))
        self.g_t3 = self.g_t3 / max_t3 if max_t3 > 1e-12 else self.g_t3
        self.z_t3 = self.z_t3 / max_t3 if max_t3 > 1e-12 else self.z_t3

        max_t5 = np.max(np.abs(self.g_t5))
        self.g_t5 = self.g_t5 / max_t5 if max_t5 > 1e-12 else self.g_t5
        self.z_t5 = self.z_t5 / max_t5 if max_t5 > 1e-12 else self.z_t5

        self.n_frames = self.g_t1.shape[0]
        self.play_running = False
        self.play_job = None
        
        # Calculate indices from metadata to avoid hardcoded global variables
        if self.mask_matrix is not None:
            self.nx, self.nz = self.mask_matrix.shape
            self.z_max_mm = self.extent_global[1]
            self.x_max_mm = self.extent_global[2]
            self.dx_mm = self.x_max_mm / self.nx
            self.dz_mm = self.z_max_mm / self.nz
            
            self.zoom_z_min = self.extent_zoom[0]
            self.zoom_z_max = self.extent_zoom[1]
            self.zoom_x_max = self.extent_zoom[2]
            self.zoom_x_min = self.extent_zoom[3]
            
            self.x_start = int(round(self.zoom_x_min / self.dx_mm))
            self.x_end = int(round(self.zoom_x_max / self.dx_mm))
            self.z_start = int(round(self.zoom_z_min / self.dz_mm))
            self.z_end = int(round(self.zoom_z_max / self.dz_mm))
        else:
            self.nx = self.nz = 0
            self.x_start = self.x_end = self.z_start = self.z_end = 0

        self.setup_ui()

    def setup_ui(self):
        self.root.title(f"NPZ Simulation Viewer — {os.path.basename(self.filepath)}")
        self.root.geometry("1300x850")

        main_frame = ttk.Frame(self.root)
        main_frame.pack(fill=tk.BOTH, expand=True, padx=5, pady=5)

        graph_frame = ttk.Frame(main_frame)
        graph_frame.pack(fill=tk.BOTH, expand=True)

        self.fig = plt.Figure(figsize=(13, 7), dpi=100, layout="constrained")
        gs = self.fig.add_gridspec(2, 3)

        self.ax_g1 = self.fig.add_subplot(gs[0, 0])
        self.ax_g3 = self.fig.add_subplot(gs[0, 1])
        self.ax_g5 = self.fig.add_subplot(gs[0, 2])
        self.ax_z1 = self.fig.add_subplot(gs[1, 0])
        self.ax_z3 = self.fig.add_subplot(gs[1, 1])
        self.ax_z5 = self.fig.add_subplot(gs[1, 2])

        vmin, vmax = -1.0, 1.0

        self.im_g1 = self.ax_g1.imshow(
            self.g_t1[0], cmap="viridis", vmin=vmin, vmax=vmax,
            aspect="auto", interpolation="nearest", extent=self.extent_global)
        self.ax_g1.set_title("Global T1")
        self.ax_g1.set_ylabel("Depth X (mm)")
        self._add_roi_rect(self.ax_g1)
        self._draw_outline(self.ax_g1, is_zoom=False)

        self.im_g3 = self.ax_g3.imshow(
            self.g_t3[0], cmap="viridis", vmin=vmin, vmax=vmax,
            aspect="auto", interpolation="nearest", extent=self.extent_global)
        self.ax_g3.set_title("Global T3")
        self._add_roi_rect(self.ax_g3)
        self._draw_outline(self.ax_g3, is_zoom=False)

        self.im_g5 = self.ax_g5.imshow(
            self.g_t5[0], cmap="viridis", vmin=vmin, vmax=vmax,
            aspect="auto", interpolation="nearest", extent=self.extent_global)
        self.ax_g5.set_title("Global T5")
        self._add_roi_rect(self.ax_g5)
        self._draw_outline(self.ax_g5, is_zoom=False)

        # Draw Probe Area (Yellow overlay on global view)
        if self.probe_z_l_mm is not None and self.probe_z_r_mm is not None:
            _pz_l = self.probe_z_l_mm
            _pz_r = self.probe_z_r_mm
        else:
            # Fallback to center if metadata is missing
            z_len_mm = self.extent_global[1]
            _pz_l = z_len_mm * 0.4
            _pz_r = z_len_mm * 0.6
        
        _probe_h = self.extent_global[2] * 0.05
        for _ax in (self.ax_g1, self.ax_g3, self.ax_g5):
            _ax.add_patch(Rectangle(
                (_pz_l, 0), _pz_r - _pz_l, _probe_h,
                linewidth=1.5, edgecolor="yellow", facecolor="yellow",
                alpha=0.45, zorder=6, label="Probe",
            ))

        # Draw Probe Center Line
        if self.probe_center_mm is not None:
            for _ax in (self.ax_g1, self.ax_g3, self.ax_g5, self.ax_z1, self.ax_z3, self.ax_z5):
                _ax.axvline(self.probe_center_mm, color="cyan", lw=1.5, ls="--",
                            zorder=8, label=f"Probe Center {self.probe_center_mm:.3f}mm")

        self.im_z1 = self.ax_z1.imshow(
            self.z_t1[0], cmap="RdBu_r", vmin=vmin, vmax=vmax,
            aspect="auto", interpolation="bilinear", extent=self.extent_zoom)
        self.ax_z1.set_title("Zoom T1")
        self.ax_z1.set_xlabel("Z (mm)")
        self.ax_z1.set_ylabel("Depth X (mm)")
        self._draw_outline(self.ax_z1, is_zoom=True)

        self.im_z3 = self.ax_z3.imshow(
            self.z_t3[0], cmap="RdBu_r", vmin=vmin, vmax=vmax,
            aspect="auto", interpolation="bilinear", extent=self.extent_zoom)
        self.ax_z3.set_title("Zoom T3")
        self.ax_z3.set_xlabel("Z (mm)")
        self._draw_outline(self.ax_z3, is_zoom=True)

        self.im_z5 = self.ax_z5.imshow(
            self.z_t5[0], cmap="RdBu_r", vmin=vmin, vmax=vmax,
            aspect="auto", interpolation="bilinear", extent=self.extent_zoom)
        self.ax_z5.set_title("Zoom T5")
        self.ax_z5.set_xlabel("Z (mm)")
        self._draw_outline(self.ax_z5, is_zoom=True)

        self.fig.colorbar(self.im_z3,
                          ax=[self.ax_g1, self.ax_g3, self.ax_g5, self.ax_z1, self.ax_z3, self.ax_z5],
                          shrink=0.9, aspect=30, label="(norm.)")

        self.canvas = FigureCanvasTkAgg(self.fig, master=graph_frame)
        self.canvas.draw()
        self.canvas.get_tk_widget().pack(fill=tk.BOTH, expand=True)

        ctrl = ttk.Frame(main_frame, relief=tk.RAISED, borderwidth=1)
        ctrl.pack(side=tk.BOTTOM, fill=tk.X, pady=5, padx=5)

        sl_box = ttk.Frame(ctrl)
        sl_box.pack(fill=tk.X, padx=10, pady=5)
        self.time_label = ttk.Label(sl_box, text="Time: 0.00 µs", width=25)
        self.time_label.pack(side=tk.LEFT)
        self.time_slider = ttk.Scale(sl_box, from_=0, to=self.n_frames - 1,
                                     orient=tk.HORIZONTAL, command=self.on_slider)
        self.time_slider.pack(side=tk.LEFT, fill=tk.X, expand=True, padx=10)

        btn = ttk.Frame(ctrl)
        btn.pack(pady=5)
        ttk.Button(btn, text="<< Start",  command=self.rewind).pack(side=tk.LEFT, padx=5)
        ttk.Button(btn, text="< Prev",    command=self.step_back).pack(side=tk.LEFT, padx=5)
        self.btn_play = ttk.Button(btn, text="Play >", command=self.toggle_play)
        self.btn_play.pack(side=tk.LEFT, padx=10)
        ttk.Button(btn, text="Next >",    command=self.step_fwd).pack(side=tk.LEFT, padx=5)

        ttk.Label(btn, text="Speed:").pack(side=tk.LEFT, padx=(20, 5))
        self.speed_var = tk.DoubleVar(value=30.0)
        ttk.Scale(btn, from_=1, to=60, variable=self.speed_var,
                  orient=tk.HORIZONTAL, length=120).pack(side=tk.LEFT)

        ttk.Button(btn, text="Save MP4", command=self.save_mp4).pack(side=tk.LEFT, padx=(20, 5))
        
        # Display info labels
        info_text = f"Frames: {self.n_frames} | dt: {self.time_step*1e6:.4f} µs"
        if self.gap_center_mm is not None and self.probe_center_mm is not None:
            diff_um = abs(self.probe_center_mm - self.gap_center_mm) * 1000
            info_text += f" | Alignment Offset: {diff_um:.1f} µm"
        ttk.Label(ctrl, text=info_text, foreground="gray").pack(side=tk.BOTTOM, pady=2)

        self.root.after(500, self.toggle_play)

    def _draw_outline(self, ax, is_zoom=False):
        if self.mask_matrix is None:
            return
        mask = self.mask_matrix[self.x_start:self.x_end, self.z_start:self.z_end] if is_zoom else self.mask_matrix
        extent = self.extent_zoom if is_zoom else self.extent_global
        if np.all(mask == 0) or np.all(mask == 1):
            return
        z_min, z_max, x_bot, x_top = extent
        rows, cols = mask.shape
        dz_px = (z_max - z_min) / cols
        dx_px = (x_bot - x_top) / rows
        lw = 1.0 if is_zoom else 0.5

        dh = np.diff(mask, axis=1)
        ri, ci = np.where(dh != 0)
        if len(ri):
            ax.vlines(z_min + (ci + 1) * dz_px,
                      x_top + ri * dx_px, x_top + (ri + 1) * dx_px,
                      colors="black", linewidths=lw, zorder=3)

        dv = np.diff(mask, axis=0)
        ri, ci = np.where(dv != 0)
        if len(ri):
            ax.hlines(x_top + (ri + 1) * dx_px,
                      z_min + ci * dz_px, z_min + (ci + 1) * dz_px,
                      colors="black", linewidths=lw, zorder=3)

    def _add_roi_rect(self, ax):
        rz, rx, rw, rh = self.roi_rect_mm
        ax.add_patch(Rectangle((rz, rx), rw, rh,
                                linewidth=1.5, edgecolor="red", facecolor="none"))

    def update_frame(self, frame_idx):
        frame_idx = int(np.clip(frame_idx, 0, self.n_frames - 1))
        self.im_g1.set_array(self.g_t1[frame_idx])
        self.im_g3.set_array(self.g_t3[frame_idx])
        self.im_g5.set_array(self.g_t5[frame_idx])
        self.im_z1.set_array(self.z_t1[frame_idx])
        self.im_z3.set_array(self.z_t3[frame_idx])
        self.im_z5.set_array(self.z_t5[frame_idx])
        self.time_label.config(text=f"Time: {frame_idx * self.time_step * 1e6:.2f} µs")
        self.canvas.draw_idle()

    def on_slider(self, val):
        self.update_frame(float(val))

    def toggle_play(self):
        if self.play_running:
            self.play_running = False
            self.btn_play.config(text="Play >")
            if self.play_job:
                self.root.after_cancel(self.play_job)
                self.play_job = None
        else:
            self.play_running = True
            self.btn_play.config(text="Pause ||")
            self._loop()

    def _loop(self):
        if not self.play_running:
            return
        nf = (int(self.time_slider.get()) + 1) % self.n_frames
        self.time_slider.set(nf)
        self.update_frame(nf)
        delay = int(1000 / max(1e-9, self.speed_var.get()))
        self.play_job = self.root.after(delay, self._loop)

    def rewind(self):
        self.play_running = False
        self.btn_play.config(text="Play >")
        self.time_slider.set(0)
        self.update_frame(0)

    def step_back(self):
        self.play_running = False
        self.btn_play.config(text="Play >")
        c = self.time_slider.get()
        self.time_slider.set(c - 1)
        self.update_frame(c - 1)

    def step_fwd(self):
        self.play_running = False
        self.btn_play.config(text="Play >")
        c = self.time_slider.get()
        self.time_slider.set(c + 1)
        self.update_frame(c + 1)

    def save_mp4(self):
        if self.play_running:
            self.toggle_play()
        fps = int(np.clip(self.speed_var.get(), 1, 60))
        mp4_path = unique_path(os.path.join(self.output_dir, f"{self.base_name}.mp4"))
        gif_path = unique_path(os.path.join(self.output_dir, f"{self.base_name}.gif"))

        def _upd(i):
            self.im_g1.set_array(self.g_t1[i])
            self.im_g3.set_array(self.g_t3[i])
            self.im_g5.set_array(self.g_t5[i])
            self.im_z1.set_array(self.z_t1[i])
            self.im_z3.set_array(self.z_t3[i])
            self.im_z5.set_array(self.z_t5[i])
            self.time_label.config(text=f"Time: {i * self.time_step * 1e6:.2f} µs")
            return [self.im_g1, self.im_g3, self.im_g5, self.im_z1, self.im_z3, self.im_z5]

        ani = animation.FuncAnimation(self.fig, _upd, frames=self.n_frames,
                                      interval=1000 / fps, blit=False)
        try:
            if animation.writers.is_available("ffmpeg"):
                ani.save(mp4_path, writer=animation.FFMpegWriter(fps=fps, bitrate=1800), dpi=100)
                messagebox.showinfo("Saved", f"MP4を保存しました:\n{mp4_path}")
            else:
                ani.save(gif_path, writer=animation.PillowWriter(fps=fps), dpi=100)
                messagebox.showwarning("Saved (GIF)", f"ffmpeg が見つからないため GIF で保存:\n{gif_path}")
        except Exception as e:
            messagebox.showerror("Save Error", f"保存に失敗:\n{e}")

def main():
    parser = argparse.ArgumentParser(description="Play back FDTD simulation NPZ data.")
    parser.add_argument("file", nargs="?", default=None, help="Path to NPZ file to play.")
    args = parser.parse_args()

    filepath = args.file

    if not filepath:
        # Show file dialog if no CLI arg is provided
        root_init = tk.Tk()
        root_init.withdraw()
        filepath = filedialog.askopenfilename(
            title="Select NPZ Simulation Data",
            filetypes=[("NPZ files", "*.npz"), ("All files", "*.*")]
        )
        root_init.destroy()
        if not filepath:
            print("No file selected. Exiting.")
            sys.exit(0)

    if not os.path.exists(filepath):
        print(f"File not found: {filepath}")
        sys.exit(1)

    print(f"Loading data from {filepath}...")
    try:
        # Load file. Large array data loading might take some memory.
        # Use mmap_mode to prevent high memory consumption initially.
        data = np.load(filepath, mmap_mode='r')
        
        # Load into dictionary so we can close the file or read it safely
        data_dict = {}
        required_keys = ["g_t1", "g_t3", "g_t5", "z_t1", "z_t3", "z_t5", "time_step", "extent_global", "extent_zoom", "roi_rect_mm"]
        
        # Check required files
        for r_key in required_keys:
            if r_key not in data.files:
                raise ValueError(f"Missing required key in NPZ file: {r_key}")
            # Pull into memory
            data_dict[r_key] = data[r_key][()] if data[r_key].ndim == 0 else np.array(data[r_key])
            
        # Load optional files
        optional_keys = ["mask_matrix", "probe_z_l_mm", "probe_z_r_mm", "probe_center_mm", "gap_center_mm", "base_name"]
        for o_key in optional_keys:
            if o_key in data.files:
                data_dict[o_key] = data[o_key][()] if data[o_key].ndim == 0 else np.array(data[o_key])

        print("Data loaded successfully. Starting GUI...")
        root = tk.Tk()
        viewer = IntegratedViewer(root, data_dict, filepath)
        root.mainloop()
        
    except Exception as e:
        print("Failed to run player:")
        traceback.print_exc()
        # Fallback to tkinter error box if tk is working
        try:
            root_err = tk.Tk()
            root_err.withdraw()
            messagebox.showerror("Load Error", f"Failed to load or play NPZ file:\n{e}\n\nCheck console for traceback.")
            root_err.destroy()
        except:
            pass

if __name__ == "__main__":
    main()
